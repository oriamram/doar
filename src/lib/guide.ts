// The guide: everything Doar can do, each in one short line.
//
// It is written to be skimmed. Every thing has the name it carries in the app and, right
// under it, what that name means in everyday words. A main entry also says how to get to
// it and what it is good for, shown only when its row is opened. Smaller things get one
// line and no more. The lengths are part of the promise, and scripts/check-guide.ts keeps
// them: a line that grows past them fails the check.
//
// The chapters follow the moments of a day with mail ("when mail arrives", "when you
// write"), not the order things were built in.

/** A place in the app that a row's button can take the reader to. */
export type Try = 'settings' | 'album' | 'spike' | 'files' | 'rules' | 'labels' | 'palette' | 'compose' | 'search' | 'ritual' | 'theme'

export type Entry = {
  /** Also the name of its picture (see GuideArt.tsx). */
  id: string
  /** What it is called in the app. */
  name: string
  /** What that means, in everyday words. */
  plain: string
  /** Where it is and when it happens. */
  how: string
  /** What it gives you. */
  why: string
  try?: Try
}

export type Small = { name: string; plain: string }

export type Chapter = {
  id: string
  /** The short name on the chapter's tag. */
  tab: string
  title: string
  entries: Entry[]
  small: Small[]
}

